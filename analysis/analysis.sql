-- Q7 Show each product's name and the total quantity sold.

SELECT P.Product_name ,SUM(O.Quantity) AS total_quantity_sold
FROM Product P
JOIN order_item O 
ON P.Product_id = O.Product_id
GROUP BY O.Product_id;

-- Q8 Find the top 5 products based on total quantity sold.

SELECT P.Product_name ,SUM(O.Quantity) AS total_quantity_sold
FROM Product P
JOIN order_item O 
ON P.Product_id = O.Product_id
GROUP BY O.Product_id
ORDER BY total_quantity_sold DESC
LIMIT 5;

-- Q9  Find the total quantity of products sold in each category.

SELECT C.Category_id , C.Category_name , SUM(O.Quantity) AS total_quantity_sold_per_category
FROM Categories C
JOIN Product P
ON C.Category_id = P.Category_id
JOIN order_item O
ON P.Product_id = O.Product_id
GROUP BY C.Category_id , C.Category_name;

-- Q10 TOTAL REVENUE BY EACH PRODUCT
-- Calculate the total revenue generated by each product.

SELECT P.Product_name , P.Product_id , SUM(O.Quantity * O.Unit_price) AS Revenue
FROM Product P
JOIN Order_item O
ON P.Product_id = O.Product_id
GROUP BY P.Product_name , P.Product_id;

-- Q11 TOTAL REVENUE BY EACH CATEGORY
-- Calculate the total revenue generated by each category.

SELECT C.Category_id , C.Category_name , SUM(O.Quantity * O.Unit_price) AS Revenue_per_category
FROM Categories C
JOIN Product P
ON C.Category_id = P.Category_id
JOIN order_item O
ON P.Product_id = O.Product_id
GROUP BY C.Category_id , C.Category_name;

-- Q12 REVENUE BY ORDER STATUS
-- Calculate the total revenue generated for each order status.

SELECT X.Order_status , SUM(O.Quantity * O.Unit_price) AS Revenue_per_order_status
FROM Orders X
JOIN order_item O
ON X.Order_id = O.Order_id
GROUP BY X.Order_status;

-- Q13 CUSTOMER SPENDING
-- How much has each customer spent across their orders?

