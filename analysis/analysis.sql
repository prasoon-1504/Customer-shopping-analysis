-- Q20 Highest-spending customer
-- Find the customer who has spent the most money.

SELECT 
    *
    FROM(
        SELECT
        C.Customer_id , 
        C.Name,
        SUM(O.Quantity * O.Unit_price) AS total_revenue_per_customer 
        FROM order_item O
        JOIN Orders 
        ON O.Order_id = Orders.Order_id
        JOIN Customer C
        ON Orders.Customer_id = C.Customer_id
        GROUP BY C.Customer_id , C.Name
        ORDER BY total_revenue_per_customer DESC
        LIMIT 1
    ) AS max_spending_per_customer;

-- Q21 Customer behavior
-- Find customers who have placed an order but have spent less than the average customer spending.

SELECT C.Customer_id , C.Name , SUM(O.Quantity * O.Unit_price) AS total_spent
FROM Customer C
JOIN Orders 
ON C.Customer_id = Orders.Customer_id
JOIN order_item O
ON Orders.Order_id = O.Order_id
GROUP BY C.Customer_id , C.Name
HAVING  SUM(O.Quantity * O.Unit_price) < 
    (
        SELECT AVG(customer_total)
        FROM (
            SELECT SUM(O.Quantity * O.Unit_price) AS customer_total
            FROM order_item O
            JOIN Orders 
            ON O.Order_id = Orders.Order_id
            JOIN Customer C 
            ON Orders.Customer_id = C.Customer_id
            GROUP BY C.Customer_id , C.Name
        ) AS Total_spending
    );

-- Q22 PAYMENT METHOD ANALYSIS
-- Calculate the total revenue generated through each payment method.


