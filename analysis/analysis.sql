-- Q23 HIGHEST ORDER VALUE
-- Find the order with the highest total value.

SELECT *
FROM(
    SELECT O.order_id , SUM(O.Quantity * O.Unit_price) AS order_value
    FROM order_item O
    GROUP BY O.Order_id
    ORDER BY order_value DESC 
    LIMIT 1
) AS order_value_table;

--  Q24 — Order composition
-- Find the orders that contain more than one different product.

SELECT O.Order_id , COUNT(O.Order_id) AS number_of_different_products
FROM order_item O
JOIN Product P
ON O.Product_id = P.Product_id
GROUP BY O.Order_id
HAVING COUNT(O.Order_id) > 1;

-- Q25 Customer order value
-- Find the customer who has placed the order with the highest value.

SELECT C.Customer_id , C.name , Orders.Order_id , SUM(O.Quantity * O.Unit_price) AS order_value
FROM order_item O
JOIN Orders 
ON O.Order_id = Orders.Order_id
JOIN Customer C
ON Orders.Customer_id = C.Customer_id
GROUP BY Orders.Order_id
ORDER BY order_value DESC
LIMIT 1;
